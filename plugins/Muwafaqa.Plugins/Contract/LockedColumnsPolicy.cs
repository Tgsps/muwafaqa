using System.Collections.Generic;
using System.Linq;

namespace Muwafaqa.Plugins.Contract
{
    /// <summary>How a guarded column is locked.</summary>
    public enum ColumnLock
    {
        /// <summary>Editable in Draft, locked in every other status (Value, Currency, Direction, Counterparty).</summary>
        AfterDraft,
        /// <summary>Written by a plug-in only: a client may not set it on Create or change it on Update, in any status
        /// (frozen USD value, approval round, contract number).</summary>
        SystemWritten,
        /// <summary>Must be supplied on Create and cannot change afterwards, in any status (Contract Type, ADR-006).</summary>
        SetOnce
    }

    /// <summary>One column guarded by the policy.</summary>
    public sealed class GuardedColumn
    {
        public string LogicalName { get; }
        public string DisplayName { get; }
        public ColumnLock Lock { get; }

        public GuardedColumn(string logicalName, string displayName, ColumnLock columnLock)
        {
            LogicalName = logicalName; DisplayName = displayName; Lock = columnLock;
        }
    }

    /// <summary>
    /// Which columns cannot be changed. Evaluated with the status the row has BEFORE the request (PreImage).
    /// A column is "changed" only if its value in the Target differs from the PreImage value.
    /// A column absent from the Target is not changed. A column absent from the PreImage is null (an image holds non-null values only).
    /// The system-written columns are written by plug-ins at PreOperation (stage 20: frozen value and round by plug-in 1, the contract
    /// number by plug-in 3); this guard runs at PreValidation (stage 10) and only sees what the client sent, so it does not block those writes.
    /// </summary>
    public static class LockedColumnsPolicy
    {
        public static readonly IReadOnlyList<GuardedColumn> Columns = new List<GuardedColumn>
        {
            new GuardedColumn(ContractColumns.Value, "Value", ColumnLock.AfterDraft),
            new GuardedColumn(ContractColumns.Currency, "Currency", ColumnLock.AfterDraft),
            new GuardedColumn(ContractColumns.Type, "Contract Type", ColumnLock.SetOnce),
            new GuardedColumn(ContractColumns.Direction, "Contract Direction", ColumnLock.AfterDraft),
            new GuardedColumn(ContractColumns.Counterparty, "Counterparty", ColumnLock.AfterDraft),
            new GuardedColumn(ContractColumns.Number, "Contract Number", ColumnLock.SystemWritten),
            new GuardedColumn(ContractColumns.ValueUsdFrozen, "Value (USD, Frozen)", ColumnLock.SystemWritten),
            new GuardedColumn(ContractColumns.ApprovalRound, "Approval Round", ColumnLock.SystemWritten),
        };

        private static string SystemWrittenText(GuardedColumn col)
        {
            if (col.LogicalName == ContractColumns.Number)
            {
                return col.DisplayName + " cannot be changed. It is generated by the system when the contract is created.";
            }
            return col.DisplayName + " cannot be changed. It is written by the system when the contract is submitted.";
        }

        private static string SetOnceText(GuardedColumn col)
        {
            return col.DisplayName + " cannot be changed after the contract is created. "
                + "Delete the Draft contract and create a new one with the right " + col.DisplayName + ".";
        }

        public static PolicyResult CheckUpdate(
            int currentStatus,
            IDictionary<string, ColumnValue> target,
            IDictionary<string, ColumnValue> preImage)
        {
            var editable = currentStatus == ContractStatus.Draft;
            var lockedNames = new List<string>();
            var otherMessages = new List<string>();

            foreach (var col in Columns)
            {
                ColumnValue t;
                if (!target.TryGetValue(col.LogicalName, out t)) continue;
                ColumnValue p;
                if (!preImage.TryGetValue(col.LogicalName, out p)) p = ColumnValue.Null;
                if (t.Equals(p)) continue;                       // identical value: no-op

                switch (col.Lock)
                {
                    case ColumnLock.SystemWritten:
                        otherMessages.Add(SystemWrittenText(col));
                        break;
                    case ColumnLock.SetOnce:
                        otherMessages.Add(SetOnceText(col));
                        break;
                    default:
                        if (!editable) lockedNames.Add(col.DisplayName);
                        break;
                }
            }

            if (lockedNames.Count == 0 && otherMessages.Count == 0) return PolicyResult.Allow;

            var parts = new List<string>();
            if (lockedNames.Count > 0)
            {
                var hint = currentStatus == ContractStatus.InForce
                    ? "An In Force contract cannot be edited."
                    : ContractStatus.IsKnown(currentStatus) ? "Return the contract to Draft first." : "The status is not one of the contract statuses.";
                parts.Add("Cannot change " + string.Join(", ", lockedNames) + " while the contract status is "
                    + ContractStatus.NameOf(currentStatus) + ". " + hint);
            }
            parts.AddRange(otherMessages);
            return PolicyResult.Deny(string.Join(" ", parts));
        }

        /// <summary>
        /// On Create: any non-empty value of a system-written column is rejected (null and an empty string count as "not supplied";
        /// the platform stores "" as null in Draft), and the set-once column (Contract Type) must be supplied, because the
        /// contract number is built from it (ADR-006).
        /// </summary>
        public static PolicyResult CheckCreate(IDictionary<string, ColumnValue> target)
        {
            var messages = new List<string>();
            foreach (var col in Columns)
            {
                ColumnValue v;
                var present = target.TryGetValue(col.LogicalName, out v);
                if (col.Lock == ColumnLock.SystemWritten)
                {
                    if (present && !v.IsNullOrEmptyText) messages.Add(SystemWrittenText(col));
                }
                else if (col.Lock == ColumnLock.SetOnce)
                {
                    if (!present || v.IsNull)
                    {
                        messages.Add(col.DisplayName + " is required. The contract number is built from it.");
                    }
                }
            }
            if (messages.Count == 0) return PolicyResult.Allow;
            return PolicyResult.Deny(string.Join(" ", messages));
        }
    }
}
